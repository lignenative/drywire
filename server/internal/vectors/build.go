package vectors

import (
	"bytes"
	"crypto/ed25519"
	"fmt"

	"github.com/lignenative/drywire/server/internal/auth"
	"github.com/lignenative/drywire/server/internal/clientref"
	"github.com/lignenative/drywire/server/internal/wire"
)

// Fixed inputs. Vectors must be reproducible, so nothing here is random;
// each key is a run of consecutive bytes, easy to recognise in a hex dump.
const (
	session      uint32 = 0x11223344
	helloCounter uint64 = 1793000000000 // a Unix time in milliseconds
	pingNumber   uint32 = 3
	clientTime   uint64 = 123456789012
	frameSamples uint32 = 240 // 5 ms at 48 kHz
)

func run(first byte, n int) []byte {
	b := make([]byte, n)
	for i := range b {
		b[i] = first + byte(i)
	}
	return b
}

// fakeFrame stands in for an Opus frame. Readable ASCII makes the vectors
// easy to check in a hex dump; the protocol never looks inside a frame.
func fakeFrame(seq uint32) []byte {
	return fmt.Appendf(nil, "opus frame %03d fake", seq)
}

// Build returns the manifest and the vector files. It is the single place
// that decides what the vectors contain.
func Build() (Manifest, map[string][]byte) {
	secret := run(0x40, wire.SecretSize)
	spaceKey := run(0x00, clientref.KeySize)
	roomID := run(0xa0, clientref.RoomIDSize)
	seed := run(0x20, ed25519.SeedSize)
	private := ed25519.NewKeyFromSeed(seed)
	public := private.Public().(ed25519.PublicKey)
	roomKey := clientref.RoomKey(spaceKey, roomID)

	m := Manifest{
		Note:            "Generated by `make vectors` (server/cmd/drywire-vectors). Do not edit by hand.",
		ProtocolVersion: wire.Version,
		Inputs: Inputs{
			Session:         session,
			SessionSecret:   secret,
			SpaceKey:        spaceKey,
			RoomID:          roomID,
			SenderSeed:      seed,
			SenderPublicKey: Hex(public),
			RoomKey:         roomKey,
		},
	}
	senderKeys := map[uint8][]byte{}
	for epoch, salt := range [][]byte{run(0x60, clientref.SaltSize), run(0x80, clientref.SaltSize)} {
		e := uint8(epoch)
		key := clientref.SenderKey(roomKey, salt, public)
		senderKeys[e] = key
		m.Epochs = append(m.Epochs, Epoch{
			Epoch:      e,
			SenderSalt: salt,
			SenderKey:  key,
			Signature:  ed25519.Sign(private, clientref.AnnouncementMessage(roomID, session, e, salt)),
		})
	}

	// Control plane: a login and an invitation link, with an instance
	// address that needs no canonicalisation.
	const instance = "https://voice.example.org"
	var challenge [auth.ChallengeSize]byte
	copy(challenge[:], run(0xc0, auth.ChallengeSize))
	login := auth.LoginMessage(challenge, instance)
	m.Login = Login{Audience: instance, Challenge: challenge[:], Message: login, Signature: ed25519.Sign(private, login)}
	code := run(0xe0, 16)
	link := clientref.InvitationLink(instance, code, spaceKey)
	payload := append(append(append([]byte{clientref.InvitationVersion}, code...), spaceKey...), instance...)
	m.Invitation = Invitation{Instance: instance, Code: code, Payload: payload, Link: link}

	files := map[string][]byte{}
	add := func(v Vector, packet []byte) {
		v.File = v.Name + ".bin"
		if h, err := wire.Parse(packet); err == nil {
			v.Header = headerFields(h)
		}
		m.Vectors = append(m.Vectors, v)
		files[v.File] = packet
	}
	audio := func(epoch, flags uint8, seq, ts uint32, p clientref.AudioPayload) ([]byte, *AudioFields) {
		plaintext, payloadFlags := p.Encode()
		h := wire.Header{Version: wire.Version, Type: wire.TypeAudio, Flags: flags | payloadFlags,
			KeyEpoch: epoch, Session: session, Sequence: seq, Timestamp: ts}
		return clientref.SealAudio(senderKeys[epoch], h, plaintext),
			&AudioFields{Plaintext: plaintext, RedundantFrame: p.Redundant, PrimaryFrame: p.Primary}
	}

	// Handshake.
	hello := wire.NewHello(session, helloCounter, secret)
	add(Vector{Name: "hello", Description: "A client binds its session to its address.",
		Hello: &HelloFields{Counter: helloCounter}}, hello)
	add(Vector{Name: "hello-ack", Description: "The relay's answer to the hello vector.",
		Hello: &HelloFields{Counter: helloCounter}}, wire.NewHelloAck(session, helloCounter, secret))
	add(Vector{Name: "hello-bad-mac", Description: "The hello vector with the last byte of its MAC flipped.",
		Error: string(wire.ErrBadMAC)}, flip(hello, wire.HelloSize-1))

	// Keepalive, ping, pong.
	keepalive := wire.NewKeepalive(session)
	add(Vector{Name: "keepalive", Description: "Keeps the session bound while the gate is closed."}, keepalive)
	add(Vector{Name: "ping", Description: "Ping number 3 carrying the client's clock.",
		Ping: &PingFields{ClientTime: clientTime}}, wire.NewPing(session, pingNumber, clientTime))
	add(Vector{Name: "pong", Description: "The relay's answer to the ping vector, after 1003 audio packets were expected.",
		Pong: &PongFields{ClientTime: clientTime, AudioReceived: 1000, AudioLost: 3}},
		wire.NewPong(session, wire.Pong{Number: pingNumber, ClientTime: clientTime, AudioReceived: 1000, AudioLost: 3}))

	// Audio.
	basic, basicFields := audio(0, 0, 7, 76800, clientref.AudioPayload{Primary: fakeFrame(7)})
	add(Vector{Name: "audio", Description: "One frame, key epoch 0, sequence 7.", Audio: basicFields}, basic)

	redundant, redundantFields := audio(0, 0, 8, 76800+frameSamples,
		clientref.AudioPayload{Redundant: fakeFrame(7), Primary: fakeFrame(8)})
	add(Vector{Name: "audio-redundant", Description: "Frame 8 carrying a copy of frame 7.",
		Audio: redundantFields}, redundant)

	lastOfSpurt, lastFields := audio(1, wire.FlagEndOfSpurt, 0, 80000, clientref.AudioPayload{Primary: fakeFrame(0)})
	add(Vector{Name: "audio-epoch-1-end-of-spurt",
		Description: "First packet of key epoch 1 (sequence restarts at 0), last of its talk spurt.",
		Audio:       lastFields}, lastOfSpurt)

	add(Vector{Name: "audio-bad-tag", Description: "The audio vector with one ciphertext byte flipped.",
		Error: string(wire.ErrBadTag)}, flip(basic, wire.HeaderSize))
	add(Vector{Name: "audio-tampered-header",
		Description: "The audio vector with its timestamp changed: the header is authenticated, so decryption fails.",
		Error:       string(wire.ErrBadTag)}, flip(basic, 15))

	// Encrypted correctly, but the redundant length (5) runs past the end.
	badFraming := clientref.SealAudio(senderKeys[0], wire.Header{Version: wire.Version, Type: wire.TypeAudio,
		Flags: wire.FlagRedundant, Session: session, Sequence: 10, Timestamp: 77520}, []byte{0x00, 0x05, 0xaa, 0xbb})
	add(Vector{Name: "audio-bad-framing",
		Description: "Decrypts, but its redundant length goes past the end of the plaintext.",
		Error:       string(wire.ErrBadFraming)}, badFraming)

	// Encrypted correctly, but its one frame is a byte over the limit.
	tooLong := clientref.SealAudio(senderKeys[0], wire.Header{Version: wire.Version, Type: wire.TypeAudio,
		Session: session, Sequence: 11, Timestamp: 77760}, make([]byte, clientref.MaxFrameSize+1))
	add(Vector{Name: "audio-frame-too-long",
		Description: "Decrypts, but its frame is longer than 575 bytes.",
		Error:       string(wire.ErrBadFraming)}, tooLong)

	// Announcements: the first one a sender sends in a room, and the same
	// packet with one salt byte changed, which breaks the signature.
	announce := clientref.NewAnnounce(private, roomID, session, 0, m.Epochs[0].SenderSalt)
	add(Vector{Name: "announce", Description: "The sender publishes the salt of key epoch 0.",
		Announce: &AnnounceFields{SenderSalt: m.Epochs[0].SenderSalt, Signature: m.Epochs[0].Signature}}, announce)
	add(Vector{Name: "announce-bad-signature",
		Description: "The announce vector with the first byte of its salt flipped: the signature no longer verifies.",
		Error:       string(wire.ErrBadSignature)}, flip(announce, wire.HeaderSize))

	// Packets that fail before any key is needed.
	tooLarge := wire.Header{Version: wire.Version, Type: wire.TypeAudio, Session: session}.Bytes()
	tooLarge = append(tooLarge, make([]byte, wire.MaxPacketSize+1-wire.HeaderSize)...)
	invalid := []struct {
		name, description string
		err               wire.Error
		packet            []byte
	}{
		{"too-short", "The keepalive vector cut to 15 bytes.", wire.ErrTooShort, keepalive[:15]},
		{"too-large", "An audio packet of 1201 bytes.", wire.ErrTooLarge, tooLarge},
		{"unsupported-version", "The keepalive vector with version 0xff.", wire.ErrUnsupportedVersion, with(keepalive, 0, 0xff)},
		{"unknown-type", "The keepalive vector with type 0x7f.", wire.ErrUnknownType, with(keepalive, 1, 0x7f)},
		{"bad-length", "The keepalive vector followed by one extra byte.", wire.ErrBadLength, append(bytes.Clone(keepalive), 0)},
		{"zero-session", "A keepalive for session 0.", wire.ErrZeroSession, wire.NewKeepalive(0)},
	}
	for _, c := range invalid {
		add(Vector{Name: c.name, Description: c.description, Error: string(c.err)}, c.packet)
	}

	// Replay window: one fresh window, steps applied in order.
	for _, s := range []struct {
		seq     uint32
		verdict wire.Verdict
	}{
		{100, wire.VerdictNew},
		{100, wire.VerdictDuplicate},
		{102, wire.VerdictNew},
		{101, wire.VerdictNew},
		{101, wire.VerdictDuplicate},
		{39, wire.VerdictNew},
		{38, wire.VerdictTooOld},
		{1000, wire.VerdictNew},
		{102, wire.VerdictTooOld},
		{999, wire.VerdictNew},
	} {
		m.ReplayWindow = append(m.ReplayWindow, ReplayStep{Sequence: s.seq, Verdict: s.verdict.String()})
	}
	return m, files
}

func headerFields(h wire.Header) *HeaderFields {
	return &HeaderFields{Version: h.Version, Type: h.Type.String(), Flags: h.Flags, KeyEpoch: h.KeyEpoch,
		Session: h.Session, Sequence: h.Sequence, Timestamp: h.Timestamp}
}

// flip returns a copy of b with byte i inverted.
func flip(b []byte, i int) []byte {
	return with(b, i, ^b[i])
}

// with returns a copy of b with byte i set to v.
func with(b []byte, i int, v byte) []byte {
	c := bytes.Clone(b)
	c[i] = v
	return c
}
